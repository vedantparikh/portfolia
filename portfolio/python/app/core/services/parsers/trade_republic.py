import io
import re
from datetime import datetime
from decimal import Decimal
from typing import List, Tuple

import pypdf

from core.errors import public_message
from core.schemas.account_statements import (
    ParsedData,
    ParsedTransaction,
    ParsingMetadata,
    SkippedRow,
    StatementPeriod,
)
from core.services.parsers.base import PDFParser

TRADE_FEE = Decimal("1")
GERMAN_MONTHS = {
    m: i
    for i, m in enumerate(
        [
            "jan",
            "feb",
            "mar",
            "apr",
            "mai",
            "jun",
            "jul",
            "aug",
            "sep",
            "okt",
            "nov",
            "dez",
        ],
        start=1,
    )
}
CASH_ROW_REASONS = {
    "Zinszahlung": "Interest on cash: portfolios have no cash account",
    "Überweisung": "Bank transfer: portfolios have no cash account",
    "Kartentransaktion": "Card payment: portfolios have no cash account",
    "Steuern": "Account-level tax: not linked to a security",
}


class TradeRepublicParser(PDFParser):
    """
    Parser for Trade Republic account statements ("Kontoauszug").
    This parser is designed to handle the specific format of PDF statements
    generated by Trade Republic Bank GmbH as of late 2025.
    """

    def _parse_german_date(self, date_str: str) -> str:
        """'06 März 2025' / '02 Jan. 2025' → '2025-03-06'; '' when unparseable."""
        match = re.match(r"^(\d{1,2})\s+([^\s\d]+?)\.?\s+(\d{4})$", date_str.strip())
        if not match:
            return ""
        day, month, year = match.groups()
        number = GERMAN_MONTHS.get(month.lower().replace("ä", "a")[:3])
        if not number:
            return ""
        try:
            return datetime(int(year), number, int(day)).strftime("%Y-%m-%d")
        except ValueError:
            return ""

    def _parse_german_number(self, num_str: str) -> Decimal:
        """Converts a German currency string to a Decimal object."""
        if not num_str:
            return Decimal("0.0")
        cleaned_str = (
            num_str.replace("€", "").replace(".", "").replace(",", ".").strip()
        )
        return Decimal(cleaned_str)

    def _parse_quantity(self, num_str: str) -> Decimal:
        """Share counts use a dot when the statement prints a fraction."""
        if "," in num_str:
            return self._parse_german_number(num_str)
        return Decimal(num_str)

    def parse(self, pdf_content: bytes) -> ParsedData:
        """Parse Trade Republic PDF statement."""
        warnings = []
        try:
            pdf_reader = pypdf.PdfReader(io.BytesIO(pdf_content))
            full_text = "".join(page.extract_text() for page in pdf_reader.pages)
        except Exception as e:
            return ParsedData(
                provider="trade_republic",
                statement_period=StatementPeriod(start_date="", end_date=""),
                transactions=[],
                metadata=ParsingMetadata(
                    total_transactions=0,
                    warnings=[public_message(e, "The PDF file could not be read")],
                ),
            )

        statement_period = self._extract_statement_period(full_text)

        transactions, skipped, parse_warnings = self._extract_transactions(full_text)
        warnings.extend(parse_warnings)

        return ParsedData(
            provider="trade_republic",
            statement_period=statement_period,
            transactions=transactions,
            skipped=skipped,
            metadata=ParsingMetadata(
                total_transactions=len(transactions),
                total_skipped=len(skipped),
                warnings=warnings,
            ),
        )

    def _extract_statement_period(self, text: str) -> StatementPeriod:
        """Extract statement period from PDF text."""
        head = text.split("UMSATZÜBERSICHT", 1)[0]
        period_match = re.search(
            r"(\d{1,2}\s+\w+\.?\s+\d{4})\s*-\s*(\d{1,2}\s+\w+\.?\s+\d{4})",
            head,
        )
        if period_match:
            start_date_str, end_date_str = period_match.groups()
            start_date = self._parse_german_date(start_date_str.strip())
            end_date = self._parse_german_date(end_date_str.strip())
            return StatementPeriod(start_date=start_date, end_date=end_date)
        return StatementPeriod(start_date="", end_date="")

    def _transaction_lines(self, content: str) -> List[str]:
        """One string per statement row.

        The PDF puts the day and month on their own line (`01 Juli` / `2025 Handel
        ...`) and, after a page break, the next row continues on the same line.
        """
        content = re.sub(r"TRADE REPUBLIC.*", "", content)
        content = re.sub(r"Seite \d+ von \d+", "", content)
        content = re.sub(r"(?m)^\s*DATUM\b.*$", "", content)
        joined: List[str] = []
        for line in content.split("\n"):
            line = line.strip()
            if not line:
                continue
            if re.match(r"^\d{1,2}\s+\w+\.?", line):
                joined.append(line)
            elif joined:
                joined[-1] = f"{joined[-1]} {line}"
        rows: List[str] = []
        splitter = re.compile(r"(?<!\d)(?=\d{1,2}\s+\w+\.?\s+\d{4})")
        for line in joined:
            rows.extend(part.strip() for part in splitter.split(line) if part.strip())
        return rows

    def _extract_transactions(
        self, full_text: str
    ) -> Tuple[List[ParsedTransaction], List[SkippedRow], List[str]]:
        """Extract transactions from PDF text."""
        transactions: List[ParsedTransaction] = []
        skipped: List[SkippedRow] = []
        warnings: List[str] = []

        transaction_block_match = re.search(
            r"UMSATZÜBERSICHT(.*?)(?:BARMITTELÜBERSICHT|HINWEISE ZUM KONTOAUSZUG)",
            full_text,
            re.DOTALL,
        )
        if not transaction_block_match:
            return [], [], ["Could not find the 'UMSATZÜBERSICHT' transaction block."]

        processed_lines = self._transaction_lines(transaction_block_match.group(1))

        known_types = (
            r"^(Handel|Zinszahlung|Erträge|Steuern|Überweisung|Kartentransaktion)"
        )

        for i, line in enumerate(processed_lines):
            line = line.replace("€", "").replace("\xa0", " ").strip()

            # Step 1: Find the date at the start of the line
            date_match = re.match(r"^(?P<date>\d{1,2}\s+\w+\.?\s+\d{4})", line)
            if not date_match:
                continue

            date_str = date_match.group("date")

            # Step 2: Find all numbers that look like money at the end of the line
            amounts_in_line = re.findall(r"[\d\.]*,\d{2}", line)
            if len(amounts_in_line) < 2:
                warnings.append(
                    f"Line {i + 1} does not contain enough monetary values: '{line[:100]}...'"
                )
                continue

            amount_str = amounts_in_line[-2]

            # Step 3: Isolate the middle part (type + description)
            try:
                amount_start_index = line.rindex(amount_str)
                middle_part = line[len(date_str) : amount_start_index].strip()
            except ValueError:
                warnings.append(
                    f"Could not isolate description in line {i + 1}: '{line[:100]}...'"
                )
                continue

            # Step 4: Find the transaction type and the description
            type_match = re.match(known_types, middle_part)
            if not type_match:
                warnings.append(
                    f"Could not determine transaction type in line {i + 1}: '{middle_part[:100]}...'"
                )
                continue

            type_str = type_match.group(1)
            desc = middle_part[len(type_str) :].strip()

            transaction_date = self._parse_german_date(date_str)
            if not transaction_date:
                warnings.append(f"Could not read the date '{date_str}' in line {i + 1}")
                continue
            total_amount = self._parse_german_number(amount_str)
            row = self._map_row(type_str, desc)
            if isinstance(row, str):
                skipped.append(
                    SkippedRow(
                        transaction_date=transaction_date,
                        kind=type_str,
                        description=desc,
                        amount=total_amount,
                        currency="EUR",
                        reason=row,
                    )
                )
                continue

            if row["transaction_type"] == "dividend":
                row.update(quantity=Decimal("0"), price=Decimal("0"))
            else:
                quantity, fee = row["quantity"], row["fees"]
                net = (
                    total_amount - fee
                    if row["transaction_type"] == "buy"
                    else total_amount + fee
                )
                row["price"] = net / quantity

            transactions.append(
                ParsedTransaction(
                    id=f"temp_{len(transactions) + 1}",
                    transaction_date=transaction_date,
                    total_amount=total_amount,
                    currency="EUR",
                    **row,
                )
            )

        return transactions, skipped, warnings

    def _map_row(self, type_str: str, desc: str) -> dict | str:
        """Fields of an importable row, or the reason it is skipped."""
        if type_str == "Handel":
            trade = re.search(
                r"(?i)(buy trade|sell trade|savings plan execution)\s+([A-Z0-9]{12})\s+(.*?),\s+quantity:\s*([\d\.,]+)",
                desc,
            )
            if not trade:
                return "Trade description not recognised"
            kind, isin, name, quantity_str = trade.groups()
            quantity = self._parse_quantity(quantity_str)
            if not quantity:
                return "Trade without a quantity"
            savings_plan = kind.lower() == "savings plan execution"
            return {
                "transaction_type": "sell" if "sell" in kind.lower() else "buy",
                "name": name.strip(),
                "symbol": isin,
                "quantity": quantity,
                "fees": Decimal("0") if savings_plan else TRADE_FEE,
            }
        if type_str == "Erträge":
            dividend = re.search(r"(?i)Cash Dividend for ISIN\s+([A-Z0-9]{12})", desc)
            if not dividend:
                return "Income row without an ISIN"
            isin = dividend.group(1)
            return {
                "transaction_type": "dividend",
                "name": f"Dividend {isin}",
                "symbol": isin,
            }
        return CASH_ROW_REASONS[type_str]
